"""镜片形状怎么来的：焦距 + 玻璃 → 曲率半径（薄透镜磨镜者公式），并与 Thorlabs 处方 / Zemax 焦距对照。
运行：python3 镜片形状核算.py"""
import math
LAM = 0.915  # μm
SELL = {  # Sellmeier 系数【资料：Schott 玻璃库】
    "N-BK7": ([1.03961212, 0.231792344, 1.01046945], [0.00600069867, 0.0200179144, 103.560653]),
    "N-SF11": ([1.73759695, 0.313747346, 1.89878101], [0.013188707, 0.0623068142, 155.23629]),
}
def n(g, l=LAM):
    B, C = SELL[g]; l2 = l * l
    return math.sqrt(1 + sum(b * l2 / (l2 - c) for b, c in zip(B, C)))
# 平凸 / 平凹：一面平（R2 = ∞）→ 1/f = (n−1)/R → R = (n−1)·f
PARTS = [("LA1907-B 平凸（长焦物镜）", "N-BK7", 77.26, 151.86), ("LC1060-B 平凹（长焦动镜）", "N-BK7", -15.43, -30.33),
         ("LA1608-B 平凸（短焦物镜）", "N-BK7", 38.63, 75.93), ("LC2265-B 平凹（短焦动镜）", "N-SF11", -11.67, -15.38)]
print(f"915 nm 折射率：N-BK7 {n('N-BK7'):.4f}，N-SF11 {n('N-SF11'):.4f}\n")
print("| 镜片 | 玻璃 | 弯面半径 R（处方） | 公式算出的焦距 | Zemax 焦距 |\n|---|---|---|---|---|")
for name, g, R, fz in PARTS:
    print(f"| {name} | {g} | {R} mm | {R/(n(g)-1):.2f} mm | {fz} mm |")
print(f"\n若 −15 mm 动镜也用 N-BK7：R 要 {-15*(n('N-BK7')-1):.2f} mm（Ø12.7 的镜片弯得太猛）→ 所以换高折射率 N-SF11，R 放宽到 −11.67 mm")
