"""高斯光束经过圆形通光孔的截光比例（核对 Zemax 结果 v0.1 的物镜口径）。
假设“4 mm 入射直径”是 1/e² 直径（待老师 / 厂家确认）；束径取 Codex 结果里“正镜首面处光束直径”。
运行：python3 口径截光.py"""
import math
CASES = [  # 方案, 距离 m, 正镜首面束径 mm【资料：Zemax 结果 v0.1】, 通光口径 mm（厂家外径 × 90%）
    ("短焦双胶合 AC254-075-B（Ø25.4）", 1, 19.992, 25.4 * 0.9),
    ("短焦双胶合 AC254-075-B（Ø25.4）", 10, 18.583, 25.4 * 0.9),
    ("长焦双胶合 AC508-150-B（Ø50.8）", 1, 23.028, 50.8 * 0.9),
]
print("| 方案 | 距离 | 束径（1/e²） | 通光口径 | 被挡掉的功率 |\n|---|---|---|---|---|")
for name, L, d, a in CASES:
    loss = math.exp(-2 * (a / 2) ** 2 / (d / 2) ** 2)          # 高斯：P(r>a) = exp(-2a²/w²)
    print(f"| {name} | {L} m | {d:.1f} mm | {a:.1f} mm | {loss*100:.1f}% |")
print("\n经验：通光口径 ≥ 1.5 × 1/e² 束径时，挡光 < 0.1%。")
